"""Original gates with verified observable synchronization after cold startup."""
import argparse
import json
from pathlib import Path
from .run import ROOT
from .confirm import freeze,generate,evaluate
from .vendor.data import Builder
from .precision_data_v2 import finish
from .data import save
from .shapes import PROFILES
from .train import write_json


def generate_v2(out):
    config=json.loads((out/'freeze.json').read_text());family=config['seed_family']
    for pi,profile in enumerate(config['profiles']):
        if not profile.startswith('uart'):continue
        base=out/'data'/f'{profile}_midstream'
        if base.with_suffix('.json').exists():continue
        b=Builder(profile,family+4000000+pi*100000)
        for i in range(101):
            b.message(b.rng.integers(0,256,4).tolist())
            if i==0:b.idle(256)
        cut=b.groups[0]['start']+37;s=finish(b,cut,family+4000000+pi*100000);save(base,s)
    generate(out)


if __name__=='__main__':
    ap=argparse.ArgumentParser();ap.add_argument('action',choices=['freeze','generate','evaluate'])
    ap.add_argument('--output',type=Path,default=ROOT/'runs'/'connectivity01');ap.add_argument('--label',required=True)
    ap.add_argument('--candidates',type=Path);ap.add_argument('--seed-family',type=int,default=331000000)
    ap.add_argument('--recipe',default='matched');ap.add_argument('--profiles',default=','.join(PROFILES))
    ap.add_argument('--workers',type=int,default=8);ap.add_argument('--arithmetic',default='float,quantized');a=ap.parse_args()
    out=a.output/'confirmations'/a.label
    if a.action=='freeze':
        freeze(a.output,a.label,json.loads(a.candidates.read_text()),a.seed_family,
            json.loads(Path(a.recipe).read_text()) if a.recipe.endswith('.json') else a.recipe,a.profiles.split(','))
        write_json(out/'startup_semantics.json',dict(version=2,observable_sync_high_ticks=256,
            payload_contract='every scored valid post-cut payload must match generated bytes',
            unchanged='all exact messages/boundaries, invalid/background rejection, timing suite and >=5/6 seeds/profile',
            correction='short mark gaps were not sufficient to guarantee synchronization from unknown UART phase'))
    elif a.action=='generate':generate_v2(out)
    else:evaluate(out,a.workers,a.arithmetic)
